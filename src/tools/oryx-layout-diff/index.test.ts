describe('run', () => {
  it('reports the layer counts and names on each side', () => {
    const out = run(both, opts());
    expect(out).toContain('Layout A: 2 layers (BASE, SYM)');
    expect(out).toContain('Layout B: 3 layers (BASE, SYM, NAV)');
    expect(out).toContain('Layers only in B: NAV');
    expect(out).toContain('Layers only in A: none');
    expect(out).toContain('Layers matched by name.');
  });

  it('finds exactly the planted changes with their physical positions', () => {
    const out = run(both, opts());
    expect(out).toContain('Layer BASE: 4 changed keys, 68 unchanged');
    expect(out).toMatch(/Left hand, row 1, col 3 \(ring\)\s+2 -> F2/);
    expect(out).toMatch(
      /Right hand, row 3, col 7 \(inner column\)\s+Shift-tap \/ Esc -> Ctrl-tap \/ Esc/,
    );
    expect(out).toMatch(/Right thumb 1 \(large\)\s+MO SYM -> Enter/);
    expect(out).toMatch(/Left thumb 4\s+Enter -> LGui/);
    expect(out).toContain('Total changed keys: 5');
    expect(out).toContain('    BASE: 4');
    expect(out).toContain('    SYM: 1');
  });

  it('treats _______ and KC_TRANSPARENT as the same binding', () => {
    const out = run(both, opts());
    // The SYM layer differs at one key only; the 69 transparent keys that
    // changed spelling must not show up.
    expect(out).toContain('Layer SYM: 1 changed key, 71 unchanged');
    expect(out).not.toContain('transparent -> transparent');
  });

  it('detects a binding that moved to another position on the same layer', () => {
    const out = run(both, opts());
    expect(out).toContain('Moved bindings:');
    expect(out).toContain('Enter: Left thumb 4 -> Right thumb 1 (large) (layer BASE)');
  });

  it('says when there are no moves', () => {
    const a = keymapFile(['BASE'], [{ key: 'BASE', tokens: BASE }]);
    const b = keymapFile(['BASE'], [{ key: 'BASE', tokens: withChanges(BASE, { 2: 'KC_F2' }) }]);
    const out = run(`${a}\n${SEPARATOR}\n${b}`, opts());
    expect(out).toContain('Moved bindings: none');
  });

  it('calls out a layer that only exists on side B', () => {
    const out = run(both, opts());
    expect(out).toContain('Layer NAV: only in layout B, 72 keys, nothing to compare it against.');
  });

  it('calls out a layer that only exists on side A', () => {
    const a = keymapFile(
      ['BASE', 'SYM'],
      [
        { key: 'BASE', tokens: BASE },
        { key: 'SYM', tokens: SYM_A },
      ],
    );
    const b = keymapFile(['BASE'], [{ key: 'BASE', tokens: BASE }]);
    const out = run(`${a}\n${SEPARATOR}\n${b}`, opts());
    expect(out).toContain('Layer SYM: only in layout A, 72 keys, nothing to compare it against.');
  });

  it('reports no changes when the two files are identical', () => {
    const out = run(`${SIDE_A}\n${SEPARATOR}\n${SIDE_A}`, opts());
    expect(out).toContain('Layer BASE: no changes, 72 keys identical');
    expect(out).toContain('Total changed keys: 0');
  });

  it('matches by file order and says so when no layer names line up', () => {
    const a = keymapFile(['ALPHA'], [{ key: 'ALPHA', tokens: BASE }]);
    const b = keymapFile(['QWERTY'], [{ key: 'QWERTY', tokens: withChanges(BASE, { 2: 'KC_F2' }) }]);
    const out = run(`${a}\n${SEPARATOR}\n${b}`, opts());
    expect(out).toContain('matched by their order in the file');
    expect(out).toContain('Layer ALPHA vs QWERTY: 1 changed key');
  });

  it('surfaces the short layer warning and falls back to key indices', () => {
    const short = BASE.slice(0, 71);
    const a = keymapFile(['BASE'], [{ key: 'BASE', tokens: short }]);
    const b = keymapFile(['BASE'], [{ key: 'BASE', tokens: withChanges(short, { 2: 'KC_F2' }) }]);
    const out = run(`${a}\n${SEPARATOR}\n${b}`, opts());
    expect(out).toContain('Warnings');
    expect(out).toContain('71 keycodes');
    expect(out).toMatch(/Key 2\s+2 -> F2/);
  });

  it('lists every key when showUnchanged is on', () => {
    const out = run(both, opts({ showUnchanged: true }));
    const baseSection = out.slice(out.indexOf('Layer BASE:'), out.indexOf('Layer SYM:'));
    const keyLines = baseSection.split('\n').filter((line) => /^ {2}[* ] /.test(line));
    expect(keyLines).toHaveLength(72);
    expect(baseSection).toContain('* ');
    expect(baseSection).toMatch(/ {2} {2}Left hand, row 1, col 1 \(pinky outer\)\s+=/);
  });

  it('emits csv with a header and quoted positions', () => {
    const out = run(both, opts({ format: 'csv' }));
    const lines = out.split('\n');
    expect(lines[0]).toBe('position,layer,old,new');
    expect(lines).toContain('"Left hand, row 1, col 3 (ring)",BASE,2,F2');
    expect(lines).toContain('Right thumb 1 (large),BASE,MO SYM,Enter');
    // Four changed keys on BASE plus one on SYM, plus the header.
    expect(lines).toHaveLength(6);
  });
});

/* ------------------------------------------------------------------ *
 * Errors
 * ------------------------------------------------------------------ */

describe('run errors', () => {
  it('throws on empty input', () => {
    expect(() => run('', opts())).toThrowError(/Nothing to compare/);
    expect(() => run('   \n  ', opts())).toThrowError(/Nothing to compare/);
  });

  it('throws when the ===== separator is missing', () => {
    expect(() => run(SIDE_A, opts())).toThrowError(/separator/);
  });

  it('throws when only one side was pasted', () => {
    expect(() => run(`${SIDE_A}\n${SEPARATOR}\n`, opts())).toThrowError(/Only one keymap.c/);
    expect(() => run(`\n${SEPARATOR}\n${SIDE_B}`, opts())).toThrowError(/Only one keymap.c/);
  });

  it('throws when a side has no layer definitions', () => {
    const notAKeymap = 'enum layers { BASE, SYM };\nint main(void) { return 0; }\n';
    expect(() => run(`${notAKeymap}\n${SEPARATOR}\n${SIDE_B}`, opts())).toThrowError(
      /Layout A has no layer definitions/,
    );
  });

  it('throws on an unknown format', () => {
    expect(() => run(both, opts({ format: 'html' }))).toThrowError(/Unknown format/);
  });
});
