describe('displayKeycode', () => {
  it('normalises plain keycodes', () => {
    expect(displayKeycode('KC_A')).toBe('A');
    expect(displayKeycode('KC_F7')).toBe('F7');
    expect(displayKeycode('KC_LSFT')).toBe('LShift');
    expect(displayKeycode('KC_SPACE')).toBe('Space');
    expect(displayKeycode('_______')).toBe('transparent');
    expect(displayKeycode('KC_TRANSPARENT')).toBe('transparent');
    expect(displayKeycode('XXXXXXX')).toBe('none');
    expect(displayKeycode('KC_NO')).toBe('none');
  });

  it('normalises layer taps and mod taps', () => {
    expect(displayKeycode('LT(1,KC_SPC)')).toBe('LT L1 / Space');
    expect(displayKeycode('LT(1, KC_SPC)', ['BASE', 'SYM'])).toBe('LT SYM / Space');
    expect(displayKeycode('MT(MOD_LSFT, KC_ESC)')).toBe('Shift-tap / Esc');
    expect(displayKeycode('LCTL_T(KC_A)')).toBe('Ctrl-tap / A');
  });

  it('names layer switches with the enum names', () => {
    const names = ['BASE', 'SYM', 'NAV'];
    expect(displayKeycode('MO(2)', names)).toBe('MO NAV');
    expect(displayKeycode('TO(0)', names)).toBe('TO BASE');
    expect(displayKeycode('TG(1)', names)).toBe('TG SYM');
    expect(displayKeycode('OSL(1)', names)).toBe('OSL SYM');
    expect(displayKeycode('MO(2)')).toBe('MO L2');
  });

  it('handles tap dance, one shot mods, wrappers and media keys', () => {
    expect(displayKeycode('TD(DANCE_0)')).toBe('Tap dance DANCE_0');
    expect(displayKeycode('OSM(MOD_LSFT)')).toBe('One-shot Shift');
    expect(displayKeycode('LSFT(KC_9)')).toBe('Shift+9');
    expect(displayKeycode('KC_MPLY')).toBe('Play/Pause');
    expect(displayKeycode('RGB_VAI')).toBe('RGB bright up');
    expect(displayKeycode('TOGGLE_LAYER_COLOR')).toBe('Toggle layer color');
  });

  it('shows unknown custom keycodes verbatim', () => {
    expect(displayKeycode('ST_MACRO_0')).toBe('ST_MACRO_0');
  });
});

