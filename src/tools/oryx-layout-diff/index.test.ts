function filled(value: string): string[] {
  return Array.from({ length: 72 }, () => value);
}

function withChanges(base: string[], changes: Record<number, string>): string[] {
  const copy = [...base];
  for (const [index, token] of Object.entries(changes)) copy[Number(index)] = token;
  return copy;
}

interface FixtureLayer {
  key: string;
  tokens: string[];
}

/** Build a keymap.c the way the Download Source zip writes one. */
function keymapFile(layerNames: string[], layers: FixtureLayer[], macro = 'LAYOUT_moonlander'): string {
  const head = [
    '/* Generated by the fixture builder. Oryx\'s own header looks like this. */',
    '#include QMK_KEYBOARD_H',
    '',
  ];
  if (layerNames.length > 0) {
    head.push('enum layers {');
    for (const name of layerNames) head.push(`    ${name}, // layer ${name}`);
    head.push('};');
    head.push('');
  }
  head.push('const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {');
  const body = layers.map(
    (layer) => `  [${layer.key}] = ${macro}(\n    ${layer.tokens.join(',\n    ')}\n  ),`,
  );
  return [...head, ...body, '};', ''].join('\n');
}

const SYM_A = withChanges(filled('_______'), {
  1: 'KC_EXLM',
  2: 'KC_AT',
  35: 'KC_HASH',
});

// Side B writes the long transparent spelling, which must not read as a change.
const SYM_B = withChanges(filled('KC_TRANSPARENT'), {
  1: 'KC_EXLM',
  2: 'KC_AT',
  35: 'KC_DLR',
});

const BASE_B = withChanges(BASE, {
  2: 'KC_F2',
  35: 'MT(MOD_LCTL, KC_ESCAPE)',
  // KC_ENTER leaves the left thumb cluster and lands on the right large thumb.
  60: 'KC_ENTER',
  68: 'KC_LGUI',
});

const SIDE_A = keymapFile(
  ['BASE', 'SYM'],
  [
    { key: 'BASE', tokens: BASE },
    { key: 'SYM', tokens: SYM_A },
  ],
);

const SIDE_B = keymapFile(
  ['BASE', 'SYM', 'NAV'],
  [
    { key: 'BASE', tokens: BASE_B },
    { key: 'SYM', tokens: SYM_B },
    { key: 'NAV', tokens: filled('KC_NO') },
  ],
);

const both = `${SIDE_A}\n${SEPARATOR}\n${SIDE_B}`;

const OPTS: OryxOpts = { showUnchanged: false, format: 'report' };
const opts = (over: Partial<OryxOpts> = {}): OryxOpts => ({ ...OPTS, ...over });

/* ------------------------------------------------------------------ *
 * Lexing
 * ------------------------------------------------------------------ */

describe('stripComments', () => {
  it('removes line and block comments', () => {
    expect(stripComments('KC_A, // KC_ZZZ\nKC_B')).not.toContain('KC_ZZZ');
    expect(stripComments('KC_A, /* KC_ZZZ */ KC_B')).not.toContain('KC_ZZZ');
    expect(stripComments('KC_A, /* KC_ZZZ */ KC_B')).toContain('KC_B');
  });

  it('leaves string literals alone', () => {
    expect(stripComments('SEND_STRING("http://example.com")')).toContain('http://example.com');
  });
});

describe('splitTopLevel', () => {
  it('splits on depth zero commas only', () => {
    expect(splitTopLevel('KC_A, LT(1, KC_SPC), MT(MOD_LSFT, KC_Z)')).toEqual([
      'KC_A',
      'LT(1, KC_SPC)',
      'MT(MOD_LSFT, KC_Z)',
    ]);
  });

  it('drops the token a trailing comma would create', () => {
    expect(splitTopLevel('KC_A, KC_B,')).toEqual(['KC_A', 'KC_B']);
  });
});

/* ------------------------------------------------------------------ *
 * Parsing
 * ------------------------------------------------------------------ */

describe('parseKeymap', () => {
  it('reads the layer count, the enum names and 72 tokens per layer', () => {
    const parsed = parseKeymap(SIDE_A, 'A');
    expect(parsed.layers).toHaveLength(2);
    expect(parsed.layers.map((layer) => layer.name)).toEqual(['BASE', 'SYM']);
    expect(parsed.layers[0].tokens).toHaveLength(72);
    expect(parsed.layers[0].tokens[35]).toBe('MT(MOD_LSFT, KC_ESCAPE)');
    expect(parsed.warnings).toEqual([]);
  });

  it('falls back to L0, L1 names when there is no layers enum', () => {
    // What Oryx actually exports: numeric layer keys and a custom_keycodes
    // enum, which must never be mistaken for a layers enum.
    const file =
      'enum custom_keycodes {\n  RGB_SLD = ML_SAFE_RANGE,\n  ST_MACRO_0,\n};\n\n' +
      keymapFile([], [{ key: '0', tokens: BASE }, { key: '1', tokens: SYM_A }], 'LAYOUT');
    const parsed = parseKeymap(file, 'A');
    expect(parsed.layers.map((layer) => layer.name)).toEqual(['L0', 'L1']);
    expect(parsed.layerNames).toEqual([]);
  });

  it('ignores keycodes hidden in comments', () => {
    const parsed = parseKeymap(SIDE_A, 'A');
    expect(parsed.layers[0].tokens.every((token) => !token.includes('layer'))).toBe(true);
  });

  it('warns and names the count when a layer is not 72 keys', () => {
    const short = BASE.slice(0, 71);
    const file = keymapFile(['BASE'], [{ key: 'BASE', tokens: short }]);
    const parsed = parseKeymap(file, 'A');
    expect(parsed.layers[0].tokens).toHaveLength(71);
    expect(parsed.warnings).toHaveLength(1);
    expect(parsed.warnings[0]).toContain('71 keycodes');
    expect(parsed.warnings[0]).toContain('Voyager');
  });
});

describe('canonicalToken', () => {
  it('collapses the transparent and none aliases', () => {
    expect(canonicalToken('_______')).toBe(canonicalToken('KC_TRANSPARENT'));
    expect(canonicalToken('KC_TRNS')).toBe(canonicalToken('KC_TRANSPARENT'));
    expect(canonicalToken('XXXXXXX')).toBe(canonicalToken('KC_NO'));
  });

  it('ignores whitespace inside nested calls', () => {
    expect(canonicalToken('LT(1, KC_SPC)')).toBe(canonicalToken('LT(1,KC_SPC)'));
  });
});

