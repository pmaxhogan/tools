/**
 * Curated OAuth scope catalog for the oauth-scope-decoder tool.
 *
 * Hand written from each provider's own scope reference. Only scopes whose
 * exact string and meaning are well established are listed; anything uncertain
 * is deliberately absent so the tool falls back to an honest "not in the
 * catalog" heuristic row instead of inventing a definition.
 *
 * `pattern` is either an exact scope string or a prefix pattern ending in `*`.
 * Exact matches always win; among prefix patterns the longest prefix wins.
 *
 * `risk` describes what the scope PERMITS. It is never a claim that a given
 * app misuses it.
 */

export type Risk = 'low' | 'moderate' | 'high' | 'critical';

export interface ScopeEntry {
  /** Exact scope string, or a prefix pattern ending in '*'. */
  pattern: string;
  /** Provider the scope belongs to, as users would name it. */
  provider: string;
  /** Short human label for the capability. */
  label: string;
  /** One sentence: what the app can DO with this. */
  plainEnglish: string;
  risk: Risk;
  /** Short reason the risk level is what it is. */
  riskWhy: string;
}

