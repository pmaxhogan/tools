/** Fast exact lookup, built once at module load. */
export const BY_PATTERN: ReadonlyMap<string, ScopeEntry> = new Map(
  SCOPES.filter((s) => !s.pattern.endsWith('*')).map((s) => [s.pattern, s]),
);

/** Same lookup, lowercased, for providers whose docs vary in case (Microsoft Graph). */
export const BY_PATTERN_LOWER: ReadonlyMap<string, ScopeEntry> = new Map(
  SCOPES.filter((s) => !s.pattern.endsWith('*')).map((s) => [s.pattern.toLowerCase(), s]),
);

/** Prefix patterns, longest first so the most specific one wins. */
export const PREFIXES: readonly ScopeEntry[] = SCOPES.filter((s) => s.pattern.endsWith('*')).slice()
  .sort((a, b) => b.pattern.length - a.pattern.length);
