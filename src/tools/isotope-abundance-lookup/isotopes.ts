/**
 * Naturally occurring isotopes of every element that has them.
 *
 * Source: NIST Physical Measurement Laboratory, "Atomic Weights and Isotopic
 * Compositions with Relative Atomic Masses" (NIST Standard Reference Database
 * 144), which republishes the IUPAC Commission on Isotopic Abundances and
 * Atomic Weights evaluations. Relative atomic masses are from the Atomic Mass
 * Evaluation; isotopic compositions are the representative values for normal
 * terrestrial material. Published uncertainties are not carried here.
 *
 * Only isotopes with a listed isotopic composition are included, so this is the
 * naturally occurring set: 288 isotopes across 84 elements. Technetium,
 * promethium and most elements past bismuth have no entry, because they have no
 * naturally occurring isotope with a measured abundance. Hydrogen 2 and
 * hydrogen 3 appear under H rather than under the symbols D and T that NIST
 * uses for them.
 *
 * The standard atomic weight is the IUPAC value. For the fourteen elements
 * whose isotopic composition varies measurably between natural sources, IUPAC
 * publishes an interval rather than a single number; `weightText` keeps that
 * interval exactly as published and `weight` holds its midpoint. Lithium is the
 * extreme case, which is why the abundance weighted average computed from the
 * representative composition sits 0.4% away from the interval midpoint.
 */

/** One isotope: mass number, relative atomic mass in u, and fractional abundance. */
export type IsotopeRow = [massNumber: number, mass: number, abundance: number];

export interface ElementIsotopes {
  atomicNumber: number;
  symbol: string;
  /** The IUPAC standard atomic weight exactly as published, interval included. */
  weightText: string;
  /** The standard atomic weight as a number; the midpoint of a published interval. */
  weight: number;
  /** Naturally occurring isotopes, in order of mass number. */
  isotopes: IsotopeRow[];
}

