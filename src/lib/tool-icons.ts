/** Fallback for tools without an icon or with an unrecognized name. */
export const DEFAULT_ICON: Component = Wrench;

/** Resolve a lucide icon name (ToolMeta.icon) to a component. */
export function iconFor(name?: string): Component {
  return (name && ICONS[name]) || DEFAULT_ICON;
}
